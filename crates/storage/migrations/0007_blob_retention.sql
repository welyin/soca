-- 迁移 7：内容对象的保留期（架构文档 §9.3、§12.3）。
--
-- §9.3 对内容仓元数据的原话是："元数据存内容引用、校验和**与保留期**"。前两样从第一版就在，
-- 保留期没有——于是 §12.3 那张表里的"对话与转写，初值 7 天"一直是一句没有落点的话：
-- 内容存下来了，而"什么时候该被清掉"没有任何地方记着。
--
-- 存的是**天数**而不是一个绝对到期时刻，也不是一个"类别名"。
--
--   存绝对时刻，等于把"什么时候该清"变成一个和读它的那一刻无关的常量，改设置就完全无效。
--   存类别名，则意味着改一次设置会让**已经写下的内容**也被追溯清理——而 §12.3 整节讲的就是
--   删除要慎重。一段被承诺"留 7 天"的对话，不该因为用户第二天把设置改成 3 天就在今晚消失。
--
--   所以：写入那一刻把天数记下来，那条承诺就固定了；改设置影响的是之后写入的内容。
--   这是一条**更保守**的选择——它不会追溯地删掉用户曾被承诺会留下的东西。要让存量内容
--   跟随新设置，那是一次显式的操作，不该是改一个数字的副作用。
--
-- 代价是扫描时不能直接用 SQL 比字符串（RFC 3339 字符串比较只在格式完全一致时才等价于时间
-- 比较，而那不是一个能被编译器保证的性质），得把行读出来在 Rust 侧算。同一件事在
-- memory_entries 的过期过滤上也是这么做的，两处保持一致。
--
-- NULL 表示不自动过期。授权文件派生索引、模型产物这类东西靠别的机制失效（证据撤回、
-- 版本替换），而不是靠一个天数——给它们编一个天数，等于假装我们知道它们该活多久。

ALTER TABLE blobs ADD COLUMN retention_days INTEGER;

-- 扫描"哪些内容该退休了"要按写入时刻走。
CREATE INDEX IF NOT EXISTS idx_blobs_retention ON blobs (retired_at_utc, created_at_utc);
